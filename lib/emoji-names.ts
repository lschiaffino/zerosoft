function normalize(s: string): string {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
}

/** ¿El emoji coincide con la búsqueda? Por nombre/palabra clave o por el propio emoji. */
export function emojiMatches(emoji: string, query: string): boolean {
  const q = normalize(query.trim());
  if (!q) return true;
  if (emoji.includes(query.trim())) return true;
  const words = normalize(EMOJI_KEYWORDS[emoji] ?? '');
  return q.split(/\s+/).every((part) => words.split(' ').some((w) => w.startsWith(part)));
}
