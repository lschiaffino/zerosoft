const NAME_BY_EMOJI = new Map<string, string>();
for (const [name, char] of Object.entries(TALK_EMOJI)) if (!NAME_BY_EMOJI.has(char)) NAME_BY_EMOJI.set(char, name);

/** `tada` → 🎉 (null si no existe). */
export function emojiFromName(name: string): string | null {
  return TALK_EMOJI[name.toLowerCase()] ?? null;
}

/** 🎉 → `tada` (el primer nombre), o el emoji tal cual si no está en la lista. */
export function emojiName(char: string): string {
  return NAME_BY_EMOJI.get(char) ?? char;
}

/** Nombres que empiezan con (o contienen) `q`, para el autocompletado de `:`. */
export function searchEmoji(q: string, limit = 8): Array<{ name: string; char: string }> {
  const needle = q.toLowerCase().replace(/^:/, '');
  if (!needle) return [];
  const starts: Array<{ name: string; char: string }> = [];
  const contains: Array<{ name: string; char: string }> = [];
  const seen = new Set<string>();
  for (const [name, char] of Object.entries(TALK_EMOJI)) {
    if (seen.has(name)) continue;
    if (name.startsWith(needle)) starts.push({ name, char });
    else if (name.includes(needle)) contains.push({ name, char });
    seen.add(name);
  }
  return [...starts, ...contains].slice(0, limit);
}

/** Una reacción válida: un emoji de la lista o un carácter de emoji corto (sin texto común). */
export function isValidReaction(emoji: string): boolean {
  if (!emoji || emoji.length > 16) return false;
  if (NAME_BY_EMOJI.has(emoji)) return true;
  return /\p{Extended_Pictographic}/u.test(emoji) && !/[A-Za-z0-9<>"'`]/.test(emoji);
}
